#include <stdio.h>
int main (){
    // Given an array, reverse it in place. Input: [1,4,3,2,6,5]  Output: [5,6,2,3,4,1]
    int arr[]={10,41,3,22,53,5};
    int n=6;
    int i;
    for (i=n-1;i>=0;i--){
        printf("%d ",arr[i]);
    }
    return 0;
}













































